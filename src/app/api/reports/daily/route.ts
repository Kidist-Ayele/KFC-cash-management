import { NextResponse } from 'next/server';
import { prisma } from '@/lib/prisma';
import { formatCurrency } from '@/lib/utils';

// GET /api/reports/daily - Generate structured daily report data & formatted message
export async function GET(request: Request) {
  try {
    const { searchParams } = new URL(request.url);
    const dateParam = searchParams.get('date');

    const startOfDay = dateParam ? new Date(dateParam) : new Date();
    startOfDay.setHours(0, 0, 0, 0);

    const endOfDay = new Date(startOfDay);
    endOfDay.setHours(23, 59, 59, 999);

    const [orders, expenses, shifts, waiters] = await Promise.all([
      prisma.order.findMany({
        where: {
          createdAt: { gte: startOfDay, lte: endOfDay },
          status: 'PAID',
        },
        include: {
          orderItems: {
            include: { menuItem: true },
          },
        },
      }),
      prisma.expense.findMany({
        where: {
          createdAt: { gte: startOfDay, lte: endOfDay },
        },
      }),
      prisma.cashierShift.findMany({
        where: {
          startedAt: { gte: startOfDay, lte: endOfDay },
        },
      }),
      prisma.waiter.findMany({ where: { isActive: true } }),
    ]);

    // 1. Sales & Revenue Calculation
    const totalSales = orders.reduce((sum, o) => sum + o.total, 0);
    const totalOrders = orders.length;

    const telebirrSales = orders
      .filter((o) => o.paymentChannel === 'TELEBIRR')
      .reduce((sum, o) => sum + o.total, 0);

    const kukuCbeSales = orders
      .filter((o) => o.paymentChannel === 'KUKU_CBE')
      .reduce((sum, o) => sum + o.total, 0);

    const samuelCbeSales = orders
      .filter((o) => o.paymentChannel === 'SAMUEL_CBE')
      .reduce((sum, o) => sum + o.total, 0);

    const cashSales = orders
      .filter((o) => o.paymentChannel === 'CASH')
      .reduce((sum, o) => sum + o.total, 0);

    const totalTips = orders.reduce((sum, o) => sum + (o.tip || 0), 0);

    // 2. Expenses Calculation
    const totalExpenses = expenses.reduce((sum, e) => sum + e.amount, 0);

    // 3. Net Daily Profit/Income (Revenue - Expenses)
    const netIncome = totalSales - totalExpenses;

    // 4. Food Item Breakdown (e.g. Special Shawarma: 15 sold)
    const itemCounts: Record<string, { name: string; quantity: number; revenue: number }> = {};
    orders.forEach((order) => {
      order.orderItems.forEach((oi) => {
        const name = oi.menuItem?.name || 'Unknown Item';
        if (!itemCounts[name]) {
          itemCounts[name] = { name, quantity: 0, revenue: 0 };
        }
        itemCounts[name].quantity += oi.quantity;
        itemCounts[name].revenue += oi.price * oi.quantity;
      });
    });

    const foodSalesList = Object.values(itemCounts).sort((a, b) => b.quantity - a.quantity);

    // 5. Generate Text Template for Telegram / WhatsApp / Email
    const dateStr = startOfDay.toLocaleDateString('en-US', {
      weekday: 'long',
      year: 'numeric',
      month: 'short',
      day: 'numeric',
    });

    let message = `🍗 *KUKU FRIED CHICKEN (KFC)*\n`;
    message += `📊 *DAILY SALES & CLOSING REPORT*\n`;
    message += `📅 Date: ${dateStr}\n\n`;

    message += `💰 *REVENUE BREAKDOWN:*\n`;
    message += `• Total Revenue: ${formatCurrency(totalSales)} (${totalOrders} orders)\n`;
    message += `• Telebirr: ${formatCurrency(telebirrSales)}\n`;
    message += `• Kuku CBE: ${formatCurrency(kukuCbeSales)}\n`;
    message += `• Samuel CBE: ${formatCurrency(samuelCbeSales)}\n`;
    message += `• Cash: ${formatCurrency(cashSales)}\n`;
    if (totalTips > 0) {
      message += `• Total Waiter Tips: ${formatCurrency(totalTips)}\n`;
    }

    message += `\n📉 *EXPENSES:*\n`;
    message += `• Total Expenses: ${formatCurrency(totalExpenses)}\n`;
    if (expenses.length > 0) {
      expenses.forEach((e) => {
        message += `  - ${e.description}: ${formatCurrency(e.amount)}\n`;
      });
    }

    message += `\n💵 *NET CASH FLOW:*\n`;
    message += `• Net Total: ${formatCurrency(netIncome)}\n`;

    message += `\n🍽️ *FOOD & DRINKS SOLD:*\n`;
    if (foodSalesList.length === 0) {
      message += `• No items sold today\n`;
    } else {
      foodSalesList.forEach((item) => {
        message += `• ${item.name}: ${item.quantity} pcs (${formatCurrency(item.revenue)})\n`;
      });
    }

    message += `\n✅ *Report Generated by KFC Cashflow Pro*`;

    return NextResponse.json({
      date: dateStr,
      summary: {
        totalSales,
        totalOrders,
        telebirrSales,
        kukuCbeSales,
        samuelCbeSales,
        cashSales,
        totalExpenses,
        totalTips,
        netIncome,
      },
      foodSalesList,
      expensesList: expenses,
      message,
    });
  } catch (error) {
    console.error('Error generating daily report:', error);
    return NextResponse.json(
      { error: 'Failed to generate daily report' },
      { status: 500 }
    );
  }
}
